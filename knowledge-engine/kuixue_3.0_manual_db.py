def build_database():
    """构建完整数据库"""
    output = {
        "meta": {
            "version": "3.0",
            "architecture": "top-down: book → direction → concept_name → stock_code",
            "created": time.strftime("%Y-%m-%d"),
            "data_status": "manually_curated",
            "description": "葵学3.0数据库：概念名称+代表性个股手动整理，非API全量数据"
        },
        "books": {}
    }

    total_directions = 0
    total_concepts = 0
    total_stocks = set()

    for book_name, book_data in BOOKS.items():
        book_entry = {
            "summary": book_data["summary"],
            "directions": {}
        }

        for dir_name, dir_data in book_data["directions"].items():
            total_directions += 1
            concepts = {}
            for concept_name, concept_info in dir_data["concepts"].items():
                total_concepts += 1
                stocks = concept_info.get("stocks", [])
                total_stocks.update(stocks)
                concepts[concept_name] = {
                    "stock_codes": stocks,
                    "stock_count": len(stocks),
                    "data_source": "manual"
                }

            book_entry["directions"][dir_name] = {
                "priority": dir_data["priority"],
                "concepts": concepts
            }

        output["books"][book_name] = book_entry

    output["meta"]["total_directions"] = total_directions
    output["meta"]["total_concepts"] = total_concepts
    output["meta"]["total_unique_stocks"] = len(total_stocks)

    return output, total_stocks


def build_stock_index(output):
    """构建反向索引：stock_code → 所属概念列表"""
    stock_index = {}
    for book_name, book_data in output["books"].items():
        for dir_name, dir_data in book_data["directions"].items():
            for concept_name, concept_info in dir_data["concepts"].items():
                for code in concept_info.get("stock_codes", []):
                    if code not in stock_index:
                        stock_index[code] = []
                    stock_index[code].append({
                        "book": book_name,
                        "direction": dir_name,
                        "concept": concept_name
                    })
    return stock_index


def main():
    output, total_stocks = build_database()

    # 保存主数据库
    output_path = os.path.join(WORKSPACE, "kuixue_book_map.json")
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)
    print(f"主数据库已保存: {output_path}")

    # 构建反向索引
    stock_index = build_stock_index(output)

    # 按覆盖概念数排序
    stock_coverage = [(code, len(entries)) for code, entries in stock_index.items()]
    stock_coverage.sort(key=lambda x: -x[1])

    # 保存反向索引
    index_path = os.path.join(WORKSPACE, "kuixue_stock_index.json")
    with open(index_path, "w", encoding="utf-8") as f:
        json.dump(stock_index, f, ensure_ascii=False, indent=2)
    print(f"反向索引已保存: {index_path}")

